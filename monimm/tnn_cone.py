"""The TNN cone versus the KL cone on the full span of permutation monomials.

Setting
-------
Every f in the n!-dimensional span of the permutation monomials x^v = x_{1,v(1)} ... x_{n,v(n)} is a
unique combination f = sum_w a_w Imm_w of Rhoades-Skandera KL immanants.  Put

    C_KL  = {f : a_w >= 0 for all w},
    C_TNN = {f : f(A) >= 0 for all A in TNN_n}.

Rhoades-Skandera (Imm_w >= 0 on TNN) give C_KL <= C_TNN.  On class functions the two cones agree for
n <= 10 (KLP_n, see :mod:`monimm.kl_extremal`).  This module asks the same question on the full span.

Charts
------
A *chart* is a sequence of elementary factors ('L', i) = I + t E_{i+1,i} and ('U', i) = I + t E_{i,i+1}
whose lower letters form a reduced word of w_0, as do its upper letters, in any interleaving: a
double reduced word of (w_0, w_0).  By Fomin-Zelevinsky, positive parameters give every totally
positive matrix, up to a positive diagonal factor D, which multiplies every monomial by det D:
f(A D) = det(D) f(A).  TP is dense in TNN.  Hence

* (certificate) if f, expanded in some chart, has only non-negative coefficients, then f >= 0 on TNN.

In a chart, Imm_w = sum_alpha kappa_alpha(w) t^alpha with kappa_alpha(w) >= 0.

Isolation
---------
Call w *TNN-isolated* if some TNN matrices A_k have Imm_v(A_k) / Imm_w(A_k) -> 0 for every v != w.
Equivalently, the coordinate vector e_w lies in the closed cone E generated by the evaluation vectors
(Imm_v(A))_v, A in TNN.  Since C_TNN is the dual cone of E,

    w is isolated  <=>  every f >= 0 on TNN has a_w >= 0.

Criterion.  The closure of the positive part of a projective toric variety is the union of the
positive torus orbits of the faces of its polytope.  So the normalised limits of evaluation vectors are
of the form sum_{alpha in F} kappa_alpha t^alpha, t > 0, for faces F of the Newton polytope of the
chart.  Their coordinates are non-negative, so a non-negative combination equal to e_w needs a face all
of whose kappa_alpha are supported on {w}, hence a *vertex* alpha with kappa_alpha supported on {w}.
Conversely such a vertex gives isolation (tropical limit t = lambda^c along an inner normal c).  So

    w is isolated  <=>  some vertex alpha of the Newton polytope has supp kappa_alpha = {w}.

:func:`isolated_set` tests this in the standard chart.  It first takes the argmax monomials of many
random linear functionals, which are always vertices, and then runs an exact LP (a strictly
separating functional) for each w still undecided.  If w is not isolated, e_w is not in E, and by
separation some f >= 0 on TNN has a_w < 0.  :func:`certified_witness` looks for such f with a chart
certificate, and :func:`verify_witness` checks a certificate in exact integer arithmetic.

Results (``check_tnn_isolation.py``)
------------------------------------
* n <= 3: every w is isolated, so C_TNN = C_KL on the full span.
* n = 4, 5: the non-isolated w are exactly the singular ones, those containing 3412 or 4231
  (2 of 24, and 32 of 120).
* n = 5: exact witnesses, i.e. f >= 0 on TNN_5 that are not KL-positive:
      Imm_15432 + Imm_43215 - Imm_45312,   Imm_21543 + Imm_54321 - Imm_52431,
      Imm_32154 + Imm_54321 - Imm_53241.
  So on the full span C_KL is strictly smaller than C_TNN, and the restriction to class functions
  in the cone conjecture KT_n is essential.

Conjecture (checked for n <= 5): w is TNN-isolated iff the Schubert variety X_w is smooth.
"""

from __future__ import annotations

import itertools
import random
from typing import Dict, Iterable, List, Sequence, Set, Tuple

import numpy as np
from flint import fmpz_mpoly_ctx
from scipy.optimize import linprog

from .kazhdan_lusztig import KazhdanLusztig, kl_immanant_coefficients

Perm = Tuple[int, ...]
Chart = List[Tuple[str, int]]


def perm_name(w: Perm) -> str:
    """One-line notation, 1-indexed, as a string: (2, 3, 0, 1) -> '3412'."""
    return "".join(str(x + 1) for x in w)


def parse_perm(s: str) -> Perm:
    return tuple(int(c) - 1 for c in s)


def contains_pattern(p: Sequence[int], pattern: Sequence[int]) -> bool:
    k = len(pattern)
    for idx in itertools.combinations(range(len(p)), k):
        vals = [p[i] for i in idx]
        if all((vals[a] < vals[b]) == (pattern[a] < pattern[b]) for a in range(k) for b in range(k)):
            return True
    return False


def is_singular(w: Perm) -> bool:
    """X_w is singular iff w contains 3412 or 4231 (Lakshmibai-Sandhya)."""
    return contains_pattern(w, (2, 3, 0, 1)) or contains_pattern(w, (3, 1, 2, 0))


def reduced_words(w: Perm) -> List[Tuple[int, ...]]:
    """All reduced words (letters i = s_i, swapping positions i, i+1) of w."""
    n = len(w)
    out: Set[Tuple[int, ...]] = set()

    def rec(p, word):
        des = [i for i in range(n - 1) if p[i] > p[i + 1]]
        if not des:
            out.add(tuple(reversed(word)))
            return
        for i in des:
            q = list(p)
            q[i], q[i + 1] = q[i + 1], q[i]
            rec(q, word + [i])

    rec(list(w), [])
    return sorted(out)


def standard_chart(n: int) -> Chart:
    word = reduced_words(tuple(range(n - 1, -1, -1)))[0]
    return [("L", i) for i in word] + [("U", i) for i in word]


def random_charts(n: int, count: int, seed: int = 0) -> Iterable[Chart]:
    """Random double reduced words of (w_0, w_0): 30% unshuffled L then U, the rest shuffled."""
    words = reduced_words(tuple(range(n - 1, -1, -1)))
    rnd = random.Random(seed)
    for _ in range(count):
        lw, uw = rnd.choice(words), rnd.choice(words)
        if rnd.random() < 0.3:
            yield [("L", i) for i in lw] + [("U", i) for i in uw]
            continue
        pos = set(rnd.sample(range(2 * len(lw)), len(lw)))
        seq, li, ui = [], 0, 0
        for p in range(2 * len(lw)):
            if p in pos:
                seq.append(("L", lw[li]))
                li += 1
            else:
                seq.append(("U", uw[ui]))
                ui += 1
        yield seq


class KLChartData:
    """KL immanants of S_n and their coefficient vectors kappa_alpha in charts."""

    def __init__(self, n: int):
        self.n = n
        self.perms: List[Perm] = list(itertools.permutations(range(n)))
        kl = KazhdanLusztig(n)
        self.klc = {w: kl_immanant_coefficients(kl, w) for w in self.perms}

    def _chart_matrix(self, seq: Chart):
        n, nv = self.n, max(len(seq), 1)
        ctx = fmpz_mpoly_ctx.get(tuple(f"z{q}" for q in range(nv)), "deglex")
        g = ctx.gens()
        one = ctx.from_dict({(0,) * nv: 1})
        zero = ctx.from_dict({})
        M = [[one if i == j else zero for j in range(n)] for i in range(n)]
        for k, (kind, i) in enumerate(seq):
            for r in range(n):          # right multiplication by the elementary factor
                if kind == "L":
                    M[r][i] = M[r][i] + g[k] * M[r][i + 1]
                else:
                    M[r][i + 1] = M[r][i + 1] + g[k] * M[r][i]
        return ctx, one, zero, M

    def _monomials(self, M, one):
        out = {}
        for v in self.perms:
            p = one
            for r in range(self.n):
                p = p * M[r][v[r]]
            out[v] = p
        return out

    def chart_coefficients(self, seq: Chart) -> Tuple[np.ndarray, np.ndarray]:
        """(K, exps): K[r, j] = kappa_{exps[r]}(perms[j]), the chart coefficients of the Imm_w."""
        _, one, zero, M = self._chart_matrix(seq)
        mono = self._monomials(M, one)
        cols = []
        for w in self.perms:
            acc = zero
            for v, c in self.klc[w].items():
                acc = acc + c * mono[v]
            cols.append({tuple(int(e) for e in ex): int(cf) for ex, cf in acc.to_dict().items()})
        exps = sorted(set(e for col in cols for e in col))
        index = {e: r for r, e in enumerate(exps)}
        K = np.zeros((len(exps), len(self.perms)))
        for j, col in enumerate(cols):
            for e, cf in col.items():
                K[index[e], j] = cf
        return K, np.array(exps, dtype=float)

    def exact_expansion(self, seq: Chart, combo: Dict[Perm, int]) -> Dict[Tuple[int, ...], int]:
        """sum_w combo[w] Imm_w in the chart, as an exact dict exponent -> integer coefficient."""
        _, one, zero, M = self._chart_matrix(seq)
        mono = self._monomials(M, one)
        f = zero
        for w, a in combo.items():
            for v, c in self.klc[w].items():
                f = f + (a * c) * mono[v]
        return {tuple(int(e) for e in ex): int(cf) for ex, cf in f.to_dict().items()}


def isolated_set(data: KLChartData, directions: int = 400_000, seed: int = 0) -> Set[Perm]:
    """The TNN-isolated w (see the module docstring), via the standard chart."""
    K, P = data.chart_coefficients(standard_chart(data.n))
    nz = (K > 0).sum(axis=1)
    single = np.full(K.shape[0], -1)
    single[nz == 1] = K[nz == 1].argmax(axis=1)
    found: Set[int] = set()
    rng = np.random.default_rng(seed)
    Pc = P - P.mean(axis=0)
    batch = 2000
    for _ in range(max(1, directions // batch)):
        top = (Pc @ rng.standard_normal((P.shape[1], batch))).argmax(axis=0)
        for r in top:
            if single[r] >= 0:
                found.add(int(single[r]))
    d = P.shape[1]
    for j in range(len(data.perms)):
        if j in found:
            continue
        for r in np.flatnonzero(single == j):
            # alpha_r is a vertex iff some c has c.(alpha_r - alpha_s) >= t > 0 for all s != r
            D = P[r] - np.delete(P, r, axis=0)
            obj = np.zeros(d + 1)
            obj[-1] = -1
            res = linprog(obj, A_ub=np.hstack([-D, np.ones((D.shape[0], 1))]),
                          b_ub=np.zeros(D.shape[0]), bounds=[(-1, 1)] * d + [(None, 1)],
                          method="highs")
            if res.status == 0 and -res.fun > 1e-9:
                found.add(j)
                break
    return {data.perms[j] for j in found}


def certified_witness(data: KLChartData, w: Perm, seq: Chart, K: np.ndarray = None):
    """LP: a_w = -1, a_v >= 0 otherwise, all chart coefficients >= 0 (minimum total weight).

    K is ``data.chart_coefficients(seq)[0]``; pass it in when testing several w in the same chart,
    since building it is the expensive step.
    Returns {v: a_v} (floating point; check with :func:`verify_witness`) or None."""
    if K is None:
        K, _ = data.chart_coefficients(seq)
    j = data.perms.index(w)
    bounds = [(0, None)] * len(data.perms)
    bounds[j] = (-1, -1)
    obj = np.ones(len(data.perms))
    obj[j] = 0
    res = linprog(obj, A_ub=-K, b_ub=np.zeros(K.shape[0]), bounds=bounds, method="highs")
    if res.status != 0:
        return None
    return {data.perms[k]: float(res.x[k]) for k in range(len(data.perms)) if abs(res.x[k]) > 1e-9}


def verify_witness(data: KLChartData, combo: Dict[Perm, int], seq: Chart) -> bool:
    """Exact check: the integer combination has only non-negative chart coefficients (so f >= 0 on
    TNN) and some negative KL coefficient (so f is not KL-positive)."""
    if not any(a < 0 for a in combo.values()):
        return False
    coeffs = data.exact_expansion(seq, combo)
    return bool(coeffs) and min(coeffs.values()) >= 0
